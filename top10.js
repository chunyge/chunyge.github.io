/* 앱 키워드 + 학습지 키워드를 합쳐요 (겹치는 말은 한 번만) */
window.withTop10 = (id, kws) => {
  const out = [], seen = new Set();
  [...(kws || []), ...((window.TOP10 || {})[id] || [])].forEach(k => {
    const n = window.kwNorm(k); if (n && !seen.has(n)) { seen.add(n); out.push(k); }
  });
  return out;
};
